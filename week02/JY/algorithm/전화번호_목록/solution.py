# [1. 문제 이해]
# - 입력값과 출력값:입력:["119", "97674223", "1195524421"], 출력:false / 입력:["123","456","789"], 출력:true
# - 핵심 조건 및 제한사항:phone_book 길이 1~1000000, 번호 길이 1~20, 같은 번호 중복 없음
# - 반드시 만족해야 하는 규칙:어떤 번호가 다른 번호의 접두어면 false, 아니면 true 반환
#
# [2. 접근 방법]
# - 고려한 방법: set에 번호 넣고 접두어를 잘라서 확인
# - 선택한 알고리즘/자료구조: 해시(set), 문자열 슬라이싱
# - 이 방법을 선택한 이유: 모든 쌍을 비교하면 100만x100만이라 시간초과남. 번호마다 앞부분을 잘라서 set에 그대로 있는지만 보면 번호 길이(최대20)만큼만 확인하면 된다
#                         짧은 문자열이 긴 문자열에 있는지 확인 X, 긴 문자열을 슬라이싱해서 ==동일한 문자열이 있는지 확인하는 것이 맞다
#
# [3. 구현 설계]
# - 처리 순서:
#   1) phone_book을 set으로 바꿔서 set_phone_book에 저장 (반복문 밖에서 한 번만)
#   2) 모든 번호 s를 돌면서 range(1,len(s))로 앞부분 s[:j]를 하나씩 자름
#   3) 자른 앞부분이 set_phone_book에 있으면 다른 번호의 접두어라는 뜻이라 answer=False
#   4) 끝까지 안 걸리면 answer=True 그대로 반환
# - 핵심 불변식 또는 정답을 보장하는 근거:접두어는 배열 순서랑 상관없이 어떤 번호든 될 수 있어서 모든 번호를 다 잘라봐야함. 자기 자신 전체는 range 끝이 len(s)라 안 잘려서 자기 자신이랑 비교되는 일은 없음
#
# [4. 복잡도]
# - 시간 복잡도:O(N x L) - N은 번호 개수, L은 번호 길이(최대 20). set에서 찾는 건 O(1)
# - 공간 복잡도:O(N) - set_phone_book에 번호 N개 저장
#
# [5. 예외 케이스]
# - 빈 값/최솟값/최댓값: 번호가 1개거나 길이가 1이면 잘라볼 앞부분이 없어서 true 반환
# - 중복 또는 경계 조건: 같은 번호는 안 들어와서 자기 자신 빼고 앞부분만 보면 된다(for j in range(1,len(s)))
#
# [6. 회고]
# - 막혔던 부분: 처음엔 set(phone_book)을 if문 안에 써서 효율성 테스트에 실패. set()은 호출할 때마다 전체를 새로 만드는 거라  반복문 밖에서 한 번만 만들어야 한다. 그리고 set은 시작하는지는 못 찾고 똑같은 값이 있는지만 찾을 수 있어서, 짧은 번호로 찾는 게 아니라 긴 번호를 잘라서 찾아야 한다.
# - 개선할 점 또는 다른 풀이: answer=False 하고 나서도 반복문이 끝까지 돌아서 찾자마자 return False 하면 더 빠름. false되자마자 return하도록 수정함.


# 문제에서 요구하는 solution 함수를 작성합니다.

def solution(phone_book):

    answer = True
    
    set_phone_book=set(phone_book)
    
    for s in phone_book:

        for j in range(1,len(s)):

            if s[:j] in set_phone_book:
                answer=False
                return answer #return
    
    return answer